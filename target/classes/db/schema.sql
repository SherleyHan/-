-- ============================================================
-- 文部科学省调查统计业务系统 数据库 Schema
-- 兼容 PostgreSQL 10+ / H2 PostgreSQL 模式
-- ============================================================

-- 用户主数据
CREATE TABLE IF NOT EXISTS m_user (
    user_id           VARCHAR(20)  PRIMARY KEY,
    user_name         VARCHAR(100) NOT NULL,
    password          VARCHAR(200) NOT NULL,
    riyousha_cd       VARCHAR(10)  NOT NULL,
    research_type     VARCHAR(10)  NOT NULL,
    authority_cd      VARCHAR(10)  NOT NULL,
    failed_count      INT          DEFAULT 0,
    account_locked    BOOLEAN      DEFAULT FALSE,
    password_expired  BOOLEAN      DEFAULT FALSE,
    password_update_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    delete_flag       BOOLEAN      DEFAULT FALSE,
    create_user       VARCHAR(20),
    create_date       TIMESTAMP    DEFAULT CURRENT_TIMESTAMP,
    update_user       VARCHAR(20),
    update_date       TIMESTAMP    DEFAULT CURRENT_TIMESTAMP
);

-- 通知邮件地址
CREATE TABLE IF NOT EXISTS notification_mail (
    id              BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    survey_type     VARCHAR(10)  NOT NULL,
    mail_address    VARCHAR(500) NOT NULL,
    file_name       VARCHAR(200),
    file_ext        VARCHAR(10),
    update_user     VARCHAR(20),
    update_date     TIMESTAMP    DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_notification_mail_survey ON notification_mail(survey_type);

-- 调查业务指示执行状态（批处理驱动）
CREATE TABLE IF NOT EXISTS directions_execution (
    execution_id    VARCHAR(30)  PRIMARY KEY,
    survey_type     VARCHAR(10)  NOT NULL,
    business_type   VARCHAR(20)  NOT NULL,
    status          VARCHAR(10)  NOT NULL DEFAULT 'WAIT',
    mail_address    VARCHAR(500),
    file_path       VARCHAR(500),
    error_message   VARCHAR(2000),
    start_time      TIMESTAMP,
    end_time        TIMESTAMP,
    create_user     VARCHAR(20),
    create_date     TIMESTAMP    DEFAULT CURRENT_TIMESTAMP,
    update_user     VARCHAR(20),
    update_date     TIMESTAMP    DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_directions_status ON directions_execution(status);
CREATE INDEX IF NOT EXISTS idx_directions_survey ON directions_execution(survey_type);

-- 文件状态表
CREATE TABLE IF NOT EXISTS file_status (
    file_id         VARCHAR(30)  PRIMARY KEY,
    file_name       VARCHAR(200) NOT NULL,
    file_ext        VARCHAR(10),
    file_size       BIGINT,
    status          VARCHAR(10)  NOT NULL DEFAULT 'WAIT',
    output_path     VARCHAR(500),
    error_message   VARCHAR(2000),
    execution_id    VARCHAR(30),
    create_date     TIMESTAMP    DEFAULT CURRENT_TIMESTAMP,
    update_date     TIMESTAMP    DEFAULT CURRENT_TIMESTAMP
);

-- 邮件发送历史
CREATE TABLE IF NOT EXISTS mail_send_history (
    id              BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mail_subject    VARCHAR(500),
    mail_to         VARCHAR(1000),
    status          VARCHAR(10),
    error_message   VARCHAR(2000),
    execution_id    VARCHAR(30),
    send_time       TIMESTAMP    DEFAULT CURRENT_TIMESTAMP
);
